import type { INestApplication } from '@nestjs/common';
import { Test } from '@nestjs/testing';
import { randomUUID } from 'node:crypto';
import { performance } from 'node:perf_hooks';
import request from 'supertest';
import { PrismaService } from '../src/prisma.service';
import { GameController } from '../src/game/game.controller';
import { SessionService, digest } from '../src/game/session.service';
import type { CurrentView } from '../src/narrative/engine';

const direct = process.env.AMI_TEST_DATABASE_URL;
const integration = direct ? describe : describe.skip;

integration('bounded human-paced Neon preview HTTP persistence smoke', () => {
  let app: INestApplication;
  let prisma: PrismaService;
  const ownedDigests: string[] = [];
  const oldPreview = process.env.AMI_DEV_PREVIEW;
  const oldAi = process.env.AMI_AI_GENERATION;
  const latencies: number[] = [];

  function connectionUrl(): string {
    if (!direct) throw Error('Isolated test database URL missing');
    const url = new URL(direct);
    if (process.env.AMI_SMOKE_USE_POOLER === '1') {
      // The CI workflow validates the direct source before allowing this opt-in.
      if (url.hostname !== 'ep-summer-field-bcnzvyx2.c-16.us-east-1.aws.neon.tech' ||
          url.pathname !== '/ami' || url.username !== 'ami_app') {
        throw Error('Refusing to switch an unapproved Neon database to pooled mode');
      }
      url.hostname = 'ep-summer-field-bcnzvyx2-pooler.c-16.us-east-1.aws.neon.tech';
    }
    return url.toString();
  }

  async function open() {
    prisma = new PrismaService({ datasourceUrl: connectionUrl() });
    const module = await Test.createTestingModule({
      controllers: [GameController],
      providers: [SessionService, { provide: PrismaService, useValue: prisma }],
    }).compile();
    const sessions = module.get(SessionService);
    const original = sessions.mutate.bind(sessions);
    jest.spyOn(sessions, 'mutate').mockImplementation(async (token, input) => {
      try { return await original(token, input); }
      catch (err) {
        // Production deliberately hides these errors; TEST-ONLY classification
        // is bounded to an error name and an optional Prisma P-code.
        const e = err as { name?: string; code?: string };
        console.error('Preview mutation diagnostic:', {
          kind: e?.name ?? 'UnknownError',
          prismaCode: /^P\d{4}$/.test(e?.code ?? '') ? e.code : null,
        });
        throw err;
      }
    });
    app = module.createNestApplication();
    await app.init();
  }

  beforeAll(async () => {
    if (process.env.VERCEL === '1') throw Error('Never run preview test inside a deployed Vercel service');
    process.env.AMI_DEV_PREVIEW = '1';
    process.env.AMI_AI_GENERATION = '0';
    await open();
  });

  afterAll(async () => {
    try {
      // Delete only sessions generated by this test, never unrelated rows.
      if (prisma && ownedDigests.length) {
        await prisma.gameSession.deleteMany({ where: { tokenDigest: { in: ownedDigests } } });
      }
    } finally {
      if (app) await app.close();
      if (oldPreview === undefined) delete process.env.AMI_DEV_PREVIEW;
      else process.env.AMI_DEV_PREVIEW = oldPreview;
      if (oldAi === undefined) delete process.env.AMI_AI_GENERATION;
      else process.env.AMI_AI_GENERATION = oldAi;
    }
  });

  it('performs ten realistic commands with replay, reload and bounded per-request latency', async () => {
    const startCreate = performance.now();
    const created = await request(app.getHttpServer()).post('/game/session')
      .send({ locale: 'pt-BR' }).expect(201);
    const header = created.get('set-cookie') as unknown as string[];
    const cookie = header[0].split(';')[0];
    ownedDigests.push(digest(cookie.split('=')[1]));
    expect(performance.now() - startCreate).toBeLessThan(5000);

    let view = created.body as CurrentView;
    const initialRevision = view.revision;
    for (let i = 0; i < 10; i++) {
      expect(view.actions.length).toBeGreaterThan(0);
      const body = { commandId: randomUUID(), expectedRevision: view.revision, actionId: view.actions[0].id };
      const started = performance.now();
      const response = await request(app.getHttpServer()).post('/game/commands').set('Cookie', cookie).send(body);
      const elapsed = performance.now() - started;
      latencies.push(elapsed);
      if (response.status >= 500) console.error('Preview HTTP failure:', { step: i + 1, status: response.status });
      expect(response.status).toBe(200);
      expect(elapsed).toBeLessThan(5000);
      expect(response.body.status).toBe('APPLIED');
      view = response.body.view as CurrentView;

      if (i === 2) {
        const replay = await request(app.getHttpServer()).post('/game/commands').set('Cookie', cookie).send(body).expect(200);
        expect(replay.body.status).toBe('REPLAYED');
        expect(replay.body.view).toEqual(view);
      }
      // A few hundred ms between actions better represents a user than a burst loop.
      await new Promise(resolve => setTimeout(resolve, 200));
    }
    expect(view.revision).toBe(initialRevision + 10);
    await request(app.getHttpServer()).get('/game/view').set('Cookie', cookie).expect(200, view);

    await app.close();
    await open();
    await request(app.getHttpServer()).get('/game/view').set('Cookie', cookie).expect(200, view);
    const row = await prisma.gameSession.findUniqueOrThrow({
      where: { tokenDigest: ownedDigests[0] },
    });
    expect(row.revision).toBe(view.revision);
    expect(await prisma.gameCommandReceipt.count({ where: { sessionId: row.id } })).toBe(10);
    const ordered = [...latencies].sort((a,b) => a-b);
    console.log('Bounded preview HTTP action latency, ms:', JSON.stringify({
      samples: ordered.length,
      median: Math.round(ordered[Math.floor(ordered.length / 2)]),
      p95: Math.round(ordered[Math.ceil(ordered.length * 0.95) - 1]),
      max: Math.round(ordered.at(-1)!),
      maximumAllowedPerRequest: 5000,
    }));
  }, 75000);
});
